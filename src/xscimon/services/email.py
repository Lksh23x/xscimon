import html
import os
from datetime import date
from sqlmodel import Session
from ..adapters.base import EmailAdapter
from ..repositories import DomainRepo, SnapshotRepo
from .digest import DigestService
import json


class EmailService:
    def __init__(self, session: Session, email_adapter: EmailAdapter):
        self._digest = DigestService(session)
        self._domains = DomainRepo(session)
        self._snapshots = SnapshotRepo(session)
        self._email = email_adapter
        self._default_to = os.environ.get("EMAIL_TO_DEFAULT", "")

    def send_digest(self, digest_date: date, domain_ids: list[int] | None,
                    post_ids: list[str] | None, to: str | None) -> dict:
        recipient = to or self._default_to
        if not recipient:
            return {"error": "No recipient address provided."}

        digest = self._digest.get_digest(digest_date)
        domains_to_include = [
            d for d in digest["domains"]
            if domain_ids is None or d["domain_id"] in domain_ids
        ]

        # Filter to selected posts if a subset was requested
        if post_ids is not None:
            post_id_set = set(post_ids)
            for d in domains_to_include:
                d["posts"] = [p for p in d["posts"] if p.get("post_id") in post_id_set]

        html = _render_email(digest_date, domains_to_include)
        subject = f"xscimon digest — {digest_date.isoformat()}"
        self._email.send(recipient, subject, html)
        return {"sent_to": recipient, "date": digest_date.isoformat(),
                "domains": len(domains_to_include)}


def _render_email(digest_date: date, domains: list[dict]) -> str:
    # Post text and handles come from X — escape everything interpolated into
    # the HTML so markup in a post can't break or inject into the email.
    sections = ""
    for d in domains:
        posts_html = "".join(
            f"<li style='margin-bottom:12px'>"
            f"<b>@{html.escape(p['author_handle'])}</b> "
            f"<span style='color:#888;font-size:0.85em'>{html.escape(p.get('created_at', '')[:10])}</span><br>"
            f"{html.escape(p['text'])}"
            f"</li>"
            for p in d["posts"]
        )
        status_color = "#22c55e" if d["status"] == "complete" else "#ef4444"
        sections += (
            f"<h2 style='border-left:4px solid {status_color};padding-left:8px'>"
            f"{html.escape(d['domain_name'])}</h2>"
            f"<ul style='list-style:none;padding:0'>{posts_html}</ul>"
        )
    return f"""<!DOCTYPE html>
<html><body style='font-family:sans-serif;max-width:680px;margin:auto;padding:24px'>
<h1>xscimon digest — {digest_date}</h1>
{sections}
<hr><p style='color:#aaa;font-size:0.8em'>Generated by xscimon</p>
</body></html>"""
